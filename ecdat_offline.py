def initialize_offline_demo(db_path: str = OFFLINE_DB, search_dir: str = ".") -> dict:
    """
    Builds ``offline_ecdat.db`` from local sources only.

    Steps:
      1. Initialize schema (safe no-op if tables exist)
      2. Scan local TLS test servers (8443, 8444, 8445)
         - If server not running: record status='local_server_offline' stub
      3. Analyze local certificate files found in search_dir
      4. Seed offline demo services & dependencies (local-only mapping)
      5. Score all assets with MWQRS
      6. Return summary of what was done

    IMPORTANT: Does NOT copy ecdat.db. Does NOT make external network calls.
    Data labelled as 'Local Demo/Test Environment' where appropriate.
    """
    summary = {
        "db_path": db_path,
        "initialized_at": datetime.now(timezone.utc).isoformat(),
        "tls_scanned": 0,
        "tls_failed": 0,
        "cert_files_analyzed": 0,
        "cert_files_failed": 0,
        "assets_total": 0,
        "errors": [],
    }

    # 1. Initialize schema
    inv.init_db(db_path)

    # 2. Scan local TLS test servers
    tls_results = []
    for host, port in LOCAL_TEST_SERVERS:
        res = scanner_core.scan_host(host, port, timeout=5.0)
        res["offline_source"] = "local_tls_scan"
        tls_results.append(res)
        if res["status"] == "success":
            summary["tls_scanned"] += 1
        else:
            summary["tls_failed"] += 1
            summary["errors"].append(
                f"TLS {host}:{port} → {res.get('status')}: {res.get('error', '')}"
            )

    # Ingest TLS results into offline DB
    if tls_results:
        _ingest_results_direct(tls_results, db_path)

    # 3. Analyze local certificate files
    cert_files = find_local_cert_files(search_dir)
    cert_results = []
    for cp in cert_files:
        cr = analyze_cert_file(cp)
        cert_results.append(cr)
        if cr["status"] == "success":
            summary["cert_files_analyzed"] += 1
        else:
            summary["cert_files_failed"] += 1
            summary["errors"].append(
                f"Cert file {cp.name} → {cr.get('error', 'parse error')}"
            )

    # Ingest cert file results (only successful ones)
    successful_cert_results = [r for r in cert_results if r["status"] == "success"]
    if successful_cert_results:
        _ingest_results_direct(successful_cert_results, db_path)

    # 4. Seed offline demo services & dependencies (local-only)
    inv.seed_offline_demo_data(db_path)

    # 5. Score all assets
    scored = score_eng.score_all_assets(db_path)
    summary["assets_total"] = len(scored)

    return summary


# ---------------------------------------------------------------------------
# Offline inventory refresh
# ---------------------------------------------------------------------------

def refresh_offline_inventory(
    db_path: str = OFFLINE_DB,
    run_code_scan: bool = True,
    code_dir: str = ".",
    search_dir: str = ".",
) -> dict:
    """
    Re-scans all local sources and updates offline_ecdat.db.

    Steps:
      1. Scan local TLS test servers
      2. Analyze local certificate files
      3. Optionally run source code scanner
      4. Re-score all assets

    Returns a summary dict.
    """
    summary = {
        "db_path": db_path,
        "refreshed_at": datetime.now(timezone.utc).isoformat(),
        "tls_scanned": 0,
        "tls_failed": 0,
        "cert_files_analyzed": 0,
        "code_findings": 0,
        "assets_total": 0,
        "errors": [],
    }

    inv.init_db(db_path)

    # 1. Local TLS scan
    tls_results = []
    for host, port in LOCAL_TEST_SERVERS:
        res = scanner_core.scan_host(host, port, timeout=5.0)
        res["offline_source"] = "local_tls_scan"
        tls_results.append(res)
        if res["status"] == "success":
            summary["tls_scanned"] += 1
        else:
            summary["tls_failed"] += 1
            summary["errors"].append(
                f"TLS {host}:{port} → {res.get('status')}: {res.get('error', '')}"
            )
    if tls_results:
        _ingest_results_direct(tls_results, db_path)

    # 2. Local cert files
    cert_files = find_local_cert_files(search_dir)
    for cp in cert_files:
        cr = analyze_cert_file(cp)
        if cr["status"] == "success":
            _ingest_results_direct([cr], db_path)
            summary["cert_files_analyzed"] += 1
        else:
            summary["errors"].append(
                f"Cert file {cp.name} → {cr.get('error', 'parse error')}"
            )

    # 3. Source code scan
    if run_code_scan:
        try:
            findings = code_eng.scan_source_directory(code_dir, db_path)
            summary["code_findings"] = len(findings)
        except Exception as e:
            summary["errors"].append(f"Code scan error: {e}")

    # Re-seed services so new TLS results get linked
    inv.seed_offline_demo_data(db_path)

    # 4. Score
    scored = score_eng.score_all_assets(db_path)
    summary["assets_total"] = len(scored)

    return summary


