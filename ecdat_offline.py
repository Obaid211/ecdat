def _get_key_info_from_public_key(public_key):
    """Return (key_type_str, key_size_bits) from a loaded public key object."""
    if isinstance(public_key, rsa.RSAPublicKey):
        return "RSA", public_key.key_size
    if isinstance(public_key, ec.EllipticCurvePublicKey):
        return f"ECC ({public_key.curve.name})", public_key.key_size
    if isinstance(public_key, dsa.DSAPublicKey):
        return "DSA", public_key.key_size
    return public_key.__class__.__name__, None


def analyze_cert_file(cert_path: Path) -> dict:
    """
    Parses a local X.509 certificate file (.pem / .crt / .cer) and returns
    a result dict in the same schema as ecdat_scanner.scan_host(), so it
    can be ingested directly via ecdat_inventory.ingest_scan_results().

    The host is set to the certificate's Common Name (or filename if absent).
    The port is set to 0 to indicate a file-based asset (not a live endpoint).
    tls_version is set to "N/A (cert file)" since no TLS handshake occurred.

    Supports both PEM and DER encoded certificates.
    """
    cert_path = Path(cert_path)
    result = {
        "host": cert_path.stem,
        "port": 0,
        "scanned_at": datetime.now(timezone.utc).isoformat(),
        "status": "unknown",
        "offline_source": "cert_file",
        "source_file": str(cert_path),
        "tls_version": "N/A (cert file)",
        "cipher_suite": None,
        "cipher_bits": None,
    }

    try:
        raw = cert_path.read_bytes()

        # Try PEM first, then DER
        cert = None
        if b"-----BEGIN CERTIFICATE-----" in raw:
            cert = x509.load_pem_x509_certificate(raw, default_backend())
        else:
            cert = x509.load_der_x509_certificate(raw, default_backend())

        key_type, key_size = _get_key_info_from_public_key(cert.public_key())

        sig_algo_raw = (
            getattr(cert.signature_algorithm_oid, "_name", None)
            or str(cert.signature_algorithm_oid)
        )
        if "ECC" in key_type and "RSA" in sig_algo_raw:
            hash_part = sig_algo_raw.split("With")[0] if "With" in sig_algo_raw else "sha256"
            sig_algo = f"ecdsa-with-{hash_part.lower()}"
        else:
            sig_algo = sig_algo_raw

        not_after = (
            cert.not_valid_after_utc
            if hasattr(cert, "not_valid_after_utc")
            else cert.not_valid_after
        )
        if not_after.tzinfo is None:
            not_after = not_after.replace(tzinfo=timezone.utc)
        days_to_expiry = (not_after - datetime.now(timezone.utc)).days

        subject = cert.subject.rfc4514_string()
        issuer = cert.issuer.rfc4514_string()

        # Use CN from subject as host name if available
        try:
            cn_attrs = cert.subject.get_attributes_for_oid(
                x509.oid.NameOID.COMMON_NAME
            )
            if cn_attrs:
                result["host"] = cn_attrs[0].value
        except Exception:
            pass

        result.update(
            {
                "status": "success",
                "cert_subject": subject,
                "cert_issuer": issuer,
                "cert_key_type": key_type,
                "cert_key_size_bits": key_size,
                "cert_signature_algorithm": sig_algo,
                "cert_not_after": not_after.isoformat(),
                "days_to_expiry": days_to_expiry,
            }
        )
        result["risk_flags"] = scanner_core.classify_risk(
            tls_version=None,
            key_type=key_type,
            key_size=key_size,
            sig_algo=sig_algo,
            days_to_expiry=days_to_expiry,
        )

    except FileNotFoundError:
        result["status"] = "error"
        result["error"] = f"Certificate file not found: {cert_path}"
    except (ValueError, Exception) as e:
        result["status"] = "error"
        result["error"] = f"Failed to parse certificate file: {e}"

    return result


def find_local_cert_files(search_dir: str = ".") -> list[Path]:
    """
    Finds certificate files in ``search_dir`` matching common extensions.
    Excludes key files and private-key material.
    """
    root = Path(search_dir)
    found = []
    for pattern in LOCAL_CERT_GLOB_PATTERNS:
        for p in root.glob(pattern):
            # Skip key files
            if "key" in p.name.lower():
                continue
            found.append(p)
    return sorted(set(found))


