"""
ECDAT — Offline Mode Engine
-----------------------------
Provides the offline sovereign-analysis capability for ECDAT.

Responsibilities:
  - Network safety guard: block external hosts in Offline Mode
  - Local TLS scanning: scan only loopback / private-network endpoints
  - Certificate file analysis: parse .pem / .crt / .cer files directly
  - Offline demo initialization: build offline_ecdat.db from local sources only
  - Offline inventory refresh: re-scan local TLS + local cert files + code

Design rules:
  - Never makes external network calls in Offline Mode
  - Never copies ecdat.db (live database) silently
  - Never silently falls back to Cached or Live mode
  - Results clearly labelled as local test / local demo where appropriate
  - The same MWQRS scoring pipeline is used as Live Mode (no fake scores)
"""

