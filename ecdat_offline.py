# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

OFFLINE_DB = "offline_ecdat.db"

# The three local test servers created by generate_test_certs.py
LOCAL_TEST_SERVERS = [
    ("127.0.0.1", 8443),  # legacy-portal.internal — RSA-1024, TLSv1.0-1.2, short expiry
    ("127.0.0.1", 8444),  # api-gateway.internal   — RSA-3072, TLSv1.2-1.3, long expiry
    ("127.0.0.1", 8445),  # auth-service.internal  — RSA-2048, TLSv1.2-1.3, medium expiry
]

# Cert files generated by generate_test_certs.py (and any pre-existing project certs)
LOCAL_CERT_GLOB_PATTERNS = ["*_cert.pem", "*.crt", "*.cer"]

# Loopback ranges that are always allowed in Offline Mode
LOOPBACK_PREFIXES = ("127.", "::1")

# RFC 1918 private ranges — allowed for local-network scanning in Offline Mode
RFC1918_NETWORKS = [
    ipaddress.ip_network("10.0.0.0/8"),
    ipaddress.ip_network("172.16.0.0/12"),
    ipaddress.ip_network("192.168.0.0/16"),
]


# ---------------------------------------------------------------------------
# Network safety guard
# ---------------------------------------------------------------------------

def is_local_host(host: str) -> bool:
    """
    Returns True if ``host`` is a loopback address, 'localhost', or falls
    within an RFC 1918 private range.

    These hosts do NOT require internet access and are allowed in Offline Mode.
    """
    h = host.strip().lower()
    if h in ("localhost", "::1"):
        return True
    for prefix in LOOPBACK_PREFIXES:
        if h.startswith(prefix):
            return True
    # Try parsing as IP and checking RFC 1918
    try:
        addr = ipaddress.ip_address(h)
        for net in RFC1918_NETWORKS:
            if addr in net:
                return True
    except ValueError:
        pass  # not a bare IP — treat as external hostname
    return False


def is_blocked_in_offline_mode(host: str) -> bool:
    """
    Returns True if the host is NOT local and therefore must be blocked
    when Offline Mode is active.

    External hostnames (google.com, wikipedia.org, etc.) and public IPs
    always return True (= blocked).
    Local loopback and RFC 1918 addresses return False (= allowed).
    """
    return not is_local_host(host)


# ---------------------------------------------------------------------------
# Local TLS scanning (loopback / LAN only)
# ---------------------------------------------------------------------------

def scan_local_tls(
    targets: Optional[list] = None,
    timeout: float = 5.0,
) -> list[dict]:
    """
    Scans a list of (host, port) tuples — ONLY local/private addresses allowed.

    Parameters
    ----------
    targets : list of (host, port), defaults to LOCAL_TEST_SERVERS
    timeout : per-connection timeout in seconds

    Returns
    -------
    list of scan result dicts (same schema as ecdat_scanner.scan_host())

    Raises
    ------
    ValueError if any target host is external (safety guard).
    """
    if targets is None:
        targets = LOCAL_TEST_SERVERS

    results = []
    for host, port in targets:
        if is_blocked_in_offline_mode(host):
            raise ValueError(
                f"OFFLINE MODE SAFETY: '{host}' is an external host. "
                "Only loopback (127.x/localhost) and RFC 1918 addresses are "
                "allowed for local TLS scanning in Offline Mode."
            )
        res = scanner_core.scan_host(host, port, timeout=timeout)
        # Tag result as local scan for display purposes
        res["offline_source"] = "local_tls_scan"
        results.append(res)

    return results


